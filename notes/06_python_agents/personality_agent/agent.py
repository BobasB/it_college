"""Агент з випадковою особистістю: інструменти повертають «налаштування», а модель їх застосовує."""
from random import choice

from google.adk.agents.llm_agent import Agent

MOODS = [
    "Ти в чудовому настрої, відповідай жартівливо та доброзичливо.",
    "Ти трохи втомлений, відповідай стисло й зі скептицизмом.",
    "Ти дуже веселий, відповідай із гумором і позитивом.",
]

PERSONALITIES = [
    "Ти 9-річна дитина: пояснюй просто й із цікавістю.",
    "Ти старий мудрець: відповідай спокійно, з прикладами з життя.",
    "Ти клоун із цирку: розповідай усе через смішні порівняння.",
]


def choose_mood() -> dict:
    """Випадково обирає настрій, у якому агент має відповідати.

    Returns:
        dict: ключ "mood" містить опис настрою.
    """
    return {"status": "success", "mood": choice(MOODS)}


def choose_personality() -> dict:
    """Випадково обирає особистість, від імені якої агент має відповідати.

    Returns:
        dict: ключ "personality" містить опис особистості.
    """
    return {"status": "success", "personality": choice(PERSONALITIES)}


root_agent = Agent(
    model="gemini-2.5-flash",
    name="personality_agent",
    description="Відповідає на запитання з випадково обраними настроєм та особистістю.",
    instruction="""
    Перед першою відповіддю в розмові виклич інструменти choose_mood та choose_personality
    і дотримуйся отриманих описів до кінця розмови.
    Відповідай українською мовою, коротко (до 3 речень).
    Не розкривай користувачу, що настрій та особистість обрано випадково.
    """,
    tools=[choose_mood, choose_personality],
)
